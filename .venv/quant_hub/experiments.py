"""Experiment runner + LEADERBOARD.md. Every config is recorded (incl. failures/no-promotion). Promotion needs: holdout RMSE
below the persistence baseline AND directional-hit binomial p < 0.05/n_configs (Bonferroni) AND positive net return after costs."""
import hashlib, json, math, os, sqlite3, sys
from datetime import datetime, timezone
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import backtest as bt

HERE = Path(__file__).resolve().parent
AGENT = "Agent_HH_Spot_EIA"


def mean_revert_20(history, features=None):
    v = [x[1] for x in history][-20:]
    return sum(v) / len(v) if len(v) >= 5 else None


MODELS = {"persistence": bt.persistence, "ar1": bt.ar1, "mean20": mean_revert_20}


def binom_p(k, n):  # two-sided exact-ish via normal approx w/ continuity; fine for n>=30
    if n == 0:
        return 1.0
    z = (abs(k - n / 2) - 0.5) / math.sqrt(n / 4)
    return math.erfc(max(z, 0) / math.sqrt(2))


def ensure(conn):
    conn.execute("""CREATE TABLE IF NOT EXISTS experiments(id TEXT PRIMARY KEY, created TEXT, config TEXT, data_version TEXT,
        train_period TEXT, val_period TEXT, test_period TEXT, metrics TEXT, baseline_metrics TEXT, promoted INTEGER, reason TEXT)""")


def run(db, n_decisions=500, horizons=(1, 5), costs=(0, 10)):
    conn = sqlite3.connect(db)
    ensure(conn)
    rows = conn.execute("SELECT DISTINCT available_timestamp FROM pit_market_data WHERE agent_id=? AND provenance='measured' "
                        "ORDER BY 1", (AGENT,)).fetchall()
    times = [r[0] for r in rows][-n_decisions:]
    dv = hashlib.sha256(f"{conn.execute('select count(*),max(available_timestamp) from pit_market_data').fetchone()}".encode()).hexdigest()[:12]
    configs = [(m, h, c) for m in MODELS for h in horizons for c in costs]
    alpha = 0.05 / max(len(configs), 1)
    res = {}
    for m, h, c in configs:
        res[(m, h, c)] = bt.walk_forward(conn, AGENT, times, h, MODELS[m], cost_bps=c)
    out = []
    for (m, h, c), r in res.items():
        tr, va, te = bt.split_chronological(r)
        met = bt.metrics(te) if te else {}
        base = bt.metrics(bt.split_chronological(res[("persistence", h, c)])[2]) if res[("persistence", h, c)] else {}
        hits = [x["dir_hit"] for x in te if x["dir_hit"] is not None]
        p = binom_p(sum(hits), len(hits))
        net = sum(x["ret"] for x in te)
        promoted = bool(m != "persistence" and met and base and met["rmse"] < base["rmse"] and p < alpha and net > 0)
        reason = "baseline" if m == "persistence" else ("promoted" if promoted else
                 f"rejected: rmse {'<' if met and base and met['rmse'] < base['rmse'] else '>='} baseline, dir_p={p:.3f} (alpha {alpha:.4f}), net_ret={net:.4f}")
        eid = hashlib.sha256(json.dumps([m, h, c, dv]).encode()).hexdigest()[:10]
        span = lambda s: f"{s[0]['target']}..{s[-1]['target']}" if s else "n/a"
        met = {**met, "dir_hit": (sum(hits) / len(hits)) if hits else None, "dir_p": p, "net_return": net}
        conn.execute("INSERT OR REPLACE INTO experiments VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                     (eid, datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), json.dumps({"model": m, "horizon_days": h, "cost_bps": c, "agent": AGENT}),
                      dv, span(tr), span(va), span(te), json.dumps(met), json.dumps(base), int(promoted), reason))
        out.append((eid, m, h, c, span(tr), span(va), span(te), met, base, promoted, reason, dv))
    conn.commit()
    write_leaderboard(out)
    return out


def write_leaderboard(out):
    f = lambda x: f"{x:.4f}" if isinstance(x, (int, float)) else "n/a"
    lines = ["# LEADERBOARD", "", "Generated by experiments.py. All configs recorded, including rejected. Series: Agent_HH_Spot_EIA (measured). "
             "Walk-forward PIT (available_timestamp <= decision), forecast scored after publication lag. Baseline: persistence. "
             "Promotion requires lower holdout RMSE than baseline, Bonferroni-corrected directional significance, and positive net return after costs.", "",
             "| ID | Model | Horizon d | Cost bps | Train | Validation | Out-of-sample | n | RMSE | Baseline RMSE | Dir hit | Dir p | Net ret | PIT data ver | Result |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for eid, m, h, c, tr, va, te, met, base, pr, reason, dv in out:
        lines.append(f"| {eid} | {m} | {h} | {c} | {tr} | {va} | {te} | {met.get('n','n/a')} | {f(met.get('rmse'))} | {f(base.get('rmse'))} | "
                     f"{f(met.get('dir_hit'))} | {f(met.get('dir_p'))} | {f(met.get('net_return'))} | {dv} | {reason} |")
    lines += ["", "No model is promoted unless the Result column says `promoted`."]
    (HERE / "LEADERBOARD.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    db = os.environ.get("DB_PATH") or str(HERE / "henry_hub_pit.db")
    for r in run(db):
        print(r[0], r[1], r[2], r[3], r[10])
